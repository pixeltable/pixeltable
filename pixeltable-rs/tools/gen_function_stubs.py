"""Generate the public stub modules `pixeltable.functions.*`, `pixeltable.iterators` and `pixeltable.io`.

Reads the upstream sources (../pixeltable) with `ast` (nothing is imported) and writes, for each public module, one
attribute per public upstream name: functions become `fn(__name__, 'name')`, which is the Rust builtin of that name
if the backend registers one and an unimplemented placeholder otherwise; classes become placeholder classes.

Usage: python tools/gen_function_stubs.py   (from pixeltable-rs/; overwrites generated files only)
"""

import ast
import sys
from pathlib import Path

RS_ROOT = Path(__file__).resolve().parent.parent
UPSTREAM = RS_ROOT.parent / 'pixeltable'
OUT = RS_ROOT / 'python' / 'pixeltable'

HEADER = '# Generated by tools/gen_function_stubs.py from the upstream module of the same name; do not edit by hand.\n'


def public_names(path: Path) -> tuple[list[str], list[str]]:
    """(function names, class names) defined at the top level of a module, in source order."""
    tree = ast.parse(path.read_text())
    explicit_all: list[str] | None = None
    funcs: list[str] = []
    classes: list[str] = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith('_'):
            if node.name not in funcs:
                funcs.append(node.name)
        elif isinstance(node, ast.ClassDef) and not node.name.startswith('_'):
            classes.append(node.name)
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name) and t.id == '__all__' and isinstance(node.value, (ast.List, ast.Tuple)):
                    explicit_all = [e.value for e in node.value.elts if isinstance(e, ast.Constant)]
    if explicit_all is not None:
        funcs = [n for n in funcs if n in explicit_all]
        classes = [n for n in classes if n in explicit_all]
    return funcs, classes


def module_source(doc: str, funcs: list[str], classes: list[str], extra: str = '') -> str:
    lines = [HEADER, f'"""{doc}"""\n', '']
    if funcs:
        lines.append('from pixeltable.functions._registry import fn as _fn')
    if classes:
        lines.append('from pixeltable._unimplemented import unimplemented_class as _cls')
    if extra:
        lines.append(extra)
    lines.append('')
    for c in classes:
        lines.append(f"{c} = _cls(__name__, '{c}')")
    for f in funcs:
        lines.append(f"{f} = _fn(__name__, '{f}')")
    return '\n'.join(lines) + '\n'


def main() -> None:
    fn_dir = UPSTREAM / 'functions'
    out_fn = OUT / 'functions'
    out_fn.mkdir(parents=True, exist_ok=True)
    submodules: list[str] = []
    for src in sorted(fn_dir.glob('*.py')):
        name = src.stem
        if name in ('__init__', 'globals'):
            continue
        funcs, classes = public_names(src)
        submodules.append(name)
        (out_fn / f'{name}.py').write_text(module_source(f'`pixeltable.functions.{name}`', funcs, classes))
    # packages (e.g. functions/video/)
    for pkg in sorted(p for p in fn_dir.iterdir() if p.is_dir() and (p / '__init__.py').exists()):
        funcs: list[str] = []
        classes: list[str] = []
        for src in sorted(pkg.glob('*.py')):
            f, c = public_names(src)
            funcs += [x for x in f if x not in funcs]
            classes += [x for x in c if x not in classes]
        submodules.append(pkg.name)
        out_pkg = out_fn / pkg.name
        out_pkg.mkdir(exist_ok=True)
        (out_pkg / '__init__.py').write_text(module_source(f'`pixeltable.functions.{pkg.name}`', funcs, classes))
    gfuncs, gclasses = public_names(fn_dir / 'globals.py')
    (out_fn / 'globals.py').write_text(module_source('General-purpose functions (`pxt.functions.count` etc.)', gfuncs, gclasses))
    init = [
        HEADER,
        '"""General Pixeltable UDFs. Function modules are stubs unless the backend implements the function."""\n',
        '# ruff: noqa: F401\n',
        'from . import (',
        *[f'    {m},' for m in sorted(submodules)],
        ')',
        f'from .globals import {", ".join(gfuncs + gclasses)}',
        'from .util import CodecContextMetadata, ContainerMetadata, StreamMetadata',
        '',
        f'__all__ = {sorted(submodules) + gfuncs + gclasses + ["CodecContextMetadata", "ContainerMetadata", "StreamMetadata"]!r}',
        '',
    ]
    (out_fn / '__init__.py').write_text('\n'.join(init))

    # iterators and io: classes / functions re-exported by the upstream package __init__
    for pkg_name in ('iterators', 'io'):
        pkg = UPSTREAM / pkg_name
        exported: dict[str, str] = {}
        tree = ast.parse((pkg / '__init__.py').read_text())
        for node in tree.body:
            if isinstance(node, ast.ImportFrom) and node.level == 1:
                for alias in node.names:
                    exported[alias.asname or alias.name] = node.module or ''
        funcs, classes = [], []
        for name, mod in exported.items():
            f, c = public_names(pkg / f'{mod}.py')
            (classes if name in c else funcs).append(name)
        out_pkg = OUT / pkg_name
        out_pkg.mkdir(exist_ok=True)
        (out_pkg / '__init__.py').write_text(module_source(f'`pixeltable.{pkg_name}` (stubs)', funcs, classes))
    print(f'generated {len(submodules)} function modules, iterators, io', file=sys.stderr)


if __name__ == '__main__':
    main()
